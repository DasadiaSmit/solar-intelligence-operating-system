import { emptyWeatherHour, sanitiseRecords } from "./normalise";
import type {
  ProviderFetchContext,
  RawProviderResult,
  WeatherProvider,
  WeatherQuery,
} from "./types";

export class DeterministicSampleProvider implements WeatherProvider {
  readonly descriptor = {
    id: "sample" as const,
    name: "Solar Intelligence deterministic sample",
    product: "Synthetic European hourly weather reference",
    version: "sample-weather-v1",
    dataClasses: ["simulation" as const],
    temporalResolutionSeconds: 3_600,
    spatialResolutionKm: null,
    attribution: "Generated by Solar Intelligence OS; not measured or forecast weather.",
    documentationUrl: "/docs/DATA_PROVIDERS.md#deterministic-sample-provider",
  };

  supports(query: WeatherQuery): boolean {
    return query.dataClass === "simulation";
  }

  async fetch(query: WeatherQuery, context: ProviderFetchContext): Promise<RawProviderResult> {
    const startMs = Date.parse(query.startUtc);
    const endMs = Date.parse(query.endUtc);
    const records = [];
    for (let timestampMs = startMs; timestampMs <= endMs; timestampMs += 3_600_000) {
      const timestamp = new Date(timestampMs);
      const record = emptyWeatherHour(timestamp.toISOString());
      const dayOfYear = Math.floor(
        (Date.UTC(timestamp.getUTCFullYear(), timestamp.getUTCMonth(), timestamp.getUTCDate()) -
          Date.UTC(timestamp.getUTCFullYear(), 0, 0)) /
          86_400_000,
      );
      const hour = timestamp.getUTCHours() + timestamp.getUTCMinutes() / 60;
      const seasonalPhase = (2 * Math.PI * (dayOfYear - 172)) / 365.2422;
      const declination = 23.44 * Math.sin((2 * Math.PI * (dayOfYear - 80)) / 365.2422);
      const solarHour = hour + query.longitude / 15;
      const hourAngle = (solarHour - 12) * 15;
      const sinElevation = Math.max(
        0,
        Math.sin(toRadians(query.latitude)) * Math.sin(toRadians(declination)) +
          Math.cos(toRadians(query.latitude)) *
            Math.cos(toRadians(declination)) *
            Math.cos(toRadians(hourAngle)),
      );
      const weatherNoise = deterministicNoise(timestampMs / 3_600_000, query.latitude, query.longitude);
      const synopticNoise = deterministicNoise(
        Math.floor(timestampMs / (18 * 3_600_000)),
        query.longitude,
        query.latitude,
      );
      const cloudCover = clamp(42 + 25 * synopticNoise + 12 * weatherNoise - 7 * Math.sin(seasonalPhase), 2, 98);
      const attenuation = 1 - 0.78 * (cloudCover / 100) ** 2.7;
      const clearGhi = 1_080 * sinElevation ** 1.12;
      const ghi = Math.max(0, clearGhi * attenuation);
      const dni =
        sinElevation > 0.02
          ? Math.max(0, Math.min(1_000, (ghi * (0.72 + 0.18 * (1 - cloudCover / 100))) / sinElevation))
          : 0;
      const dhi = Math.max(0, ghi - dni * sinElevation);
      const temperature =
        11.5 +
        8.5 * Math.sin(seasonalPhase) +
        3.2 * Math.sin((2 * Math.PI * (solarHour - 8)) / 24) +
        weatherNoise * 1.8 -
        Math.max(0, Math.abs(query.latitude) - 52) * 0.18;
      const precipitation = cloudCover > 78 && weatherNoise > 0.2 ? (weatherNoise - 0.2) * 2.2 : 0;

      record.temperatureC = round(temperature, 2);
      record.relativeHumidityPct = round(clamp(78 - temperature * 1.05 + cloudCover * 0.18, 30, 100), 1);
      record.cloudCoverPct = round(cloudCover, 1);
      record.precipitationMm = round(precipitation, 2);
      record.snowDepthCm = temperature < 0 && precipitation > 0 ? round(precipitation * 0.7, 2) : 0;
      record.surfacePressureHpa = round(1_014 + synopticNoise * 12, 1);
      record.windSpeedMps = round(clamp(4.2 + Math.abs(weatherNoise) * 3.8 + cloudCover * 0.015, 0, 28), 2);
      record.ghiWm2 = round(ghi, 2);
      record.dniWm2 = round(dni, 2);
      record.dhiWm2 = round(dhi, 2);
      record.qualityFlags.push("synthetic:deterministic_sample");
      records.push(record);
    }

    return {
      provider: this.descriptor,
      actualDataClass: "simulation",
      records: sanitiseRecords(records),
      issueTimeUtc: null,
      retrievalTimeUtc: context.now().toISOString(),
      assumptions: [
        "Deterministic analytic seasonality and cloud regimes are used for interface and pipeline testing.",
        "The series is not calibrated to a measured site and must not be used for investment decisions.",
        "Irradiance is a bounded synthetic clear-sky envelope with deterministic cloud attenuation.",
      ],
      transformations: [
        "UTC hourly grid generation",
        "deterministic solar-elevation approximation",
        "bounded physical-range validation",
      ],
      warnings: [
        "SIMULATED DATA — this dataset is neither an observation, a reanalysis, nor an issued forecast.",
      ],
      rawPayload: {
        generator: this.descriptor.version,
        query,
      },
      transport: { httpStatus: 200, retryCount: 0 },
    };
  }
}

function deterministicNoise(index: number, a: number, b: number): number {
  const raw = Math.sin(index * 12.9898 + a * 78.233 + b * 37.719) * 43_758.5453;
  return (raw - Math.floor(raw)) * 2 - 1;
}

function toRadians(value: number): number {
  return (value * Math.PI) / 180;
}

function clamp(value: number, minimum: number, maximum: number): number {
  return Math.min(maximum, Math.max(minimum, value));
}

function round(value: number, digits: number): number {
  const scale = 10 ** digits;
  return Math.round(value * scale) / scale;
}

