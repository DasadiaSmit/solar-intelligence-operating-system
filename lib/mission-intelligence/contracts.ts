export interface EvidenceRefV1 {
  /** Globally unique reference ID used by every finding and measurement. */
  id: string;
  /** Immutable result/study/run identifier enclosing the referenced fact. */
  resultId: string;
  sourceType: MissionEvidenceSourceType;
  sourceId: string;
  /** Stable, registered fact key; never free-form instructions. */
  factKey: string;
  /** Canonical resolver locator generated by an approved evidence adapter. */
  locator: string;
  label: string;
  domain: EvidenceDomain;
  lifecycle: ScientificLifecycle;
  dataClass: ScientificDataClass;
  provider: {
    id: string;
    name: string;
    product: string;
    version: string;
  };
  model: {
    id: string | null;
    name: string | null;
    version: string | null;
  };
  issueTimeUtc: string | null;
  validRangeUtc: readonly [string, string] | null;
  timestampUtc: string | null;
  resolution: string;
  /** Required for numerical facts; use "dimensionless" where appropriate. */
  unit: string | null;
  quality: {
    score: number | null;
    completeness: number | null;
    flags: readonly string[];
  };
  provenance: {
    verified: boolean;
    snapshotIds: readonly string[];
    datasetVersion: string | null;
    calculationVersion: string | null;
    contentHash: string | null;
  };
}

